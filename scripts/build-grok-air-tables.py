#!/usr/bin/env python3
"""Grok fork: compact real-air blowdown tables for the fast landing page (grok/air-tables.js).

Requires CoolProp 8.0.0. For each fill temperature, 250 kg of air in 600 L follows an adiabatic,
well-mixed (isentropic) blowdown. For three discharge modes we tabulate cumulative gas used and
cumulative impulse, so the browser never needs the 1.5 MB reference tables on the critical path.

Modes (effective exhaust velocity ve = thrust / mass flow):
  reg100 : isenthalpic regulator to 100 bar, then a choked convergent nozzle (Anders Bjarby's default topology)
  sonic  : unregulated blowdown through choked convergent nozzles down to 10 bar tank pressure
  bell   : unregulated, ideal-gas bell nozzle with area ratio 10 (best case), down to 10 bar
Nozzle relations are ideal-gas (gamma = 1.4) using the real-gas stagnation temperature.
"""
import json, math
from pathlib import Path
import CoolProp
from CoolProp.CoolProp import PropsSI as P
assert CoolProp.__version__ == '8.0.0'
OUT = Path(__file__).resolve().parent.parent / 'grok' / 'air-tables.js'
F = 'Air'; V = 0.6; M0 = 250.0; PA = 101325.0; G = 1.4; R = 287.05
GAM = math.sqrt(G) * (2 / (G + 1)) ** ((G + 1) / (2 * (G - 1)))
def cf_sonic(pc):
    r = (2 / (G + 1)) ** (G / (G - 1))
    return GAM * math.sqrt(2 * G / (G - 1) * (1 - r ** ((G - 1) / G))) + (r - PA / pc)
def ve_sonic(T, pc): return cf_sonic(pc) * math.sqrt(R * T) / GAM
def ve_bell(T, pc, eps=10.0):
    ar = lambda M: (1 / M) * ((2 / (G + 1)) * (1 + (G - 1) / 2 * M * M)) ** ((G + 1) / (2 * (G - 1)))
    lo, hi = 1.0, 10.0
    for _ in range(80):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if ar(mid) < eps else (lo, mid)
    M = lo; k = 1 + (G - 1) / 2 * M * M
    pe = pc * k ** (-G / (G - 1)); Te = T / k
    return M * math.sqrt(G * R * Te) + (pe - PA) * eps / (pc * GAM / math.sqrt(R * T))
DM = 2.5
out = {'meta': {'fluid': 'Air (CoolProp HEOS pseudo-pure, Lemmon et al. 2000)', 'CoolProp': CoolProp.__version__,
       'tankVolume_L': 600, 'gas_kg': M0, 'step_kg': DM, 'process': 'isentropic tank blowdown',
       'modes': {'reg100': 'regulated 100 bar, sonic nozzle', 'sonic': 'unregulated, sonic nozzle, to 10 bar', 'bell': 'unregulated, bell nozzle eps=10, to 10 bar'}},
       'temps': []}
for TC in [-10, 0, 10, 20, 30, 40]:
    T0 = TC + 273.15; rho0 = M0 / V
    s0 = P('S', 'D', rho0, 'T', T0, F); p0 = P('P', 'D', rho0, 'T', T0, F)
    row = {'T0C': TC, 'p0_bar': round(p0 / 1e5, 1), 'used': [], 'p_bar': [], 'T_C': [], 'I': {'reg100': [0.0], 'sonic': [0.0], 'bell': [0.0]}}
    alive = {'reg100': True, 'sonic': True, 'bell': True}
    m = M0
    while m - DM > 0:
        rho = (m - DM / 2) / V
        try:
            T = P('T', 'D', rho, 'S', s0, F); p = P('P', 'D', rho, 'S', s0, F); h = P('H', 'D', rho, 'S', s0, F)
        except ValueError:
            break
        ves = {}
        if alive['reg100'] and p > 100e5 * 1.02:
            try: ves['reg100'] = ve_sonic(P('T', 'P', 100e5, 'H', h, F), 100e5)
            except ValueError: pass
        if p > 10e5:
            ves['sonic'] = ve_sonic(T, p); ves['bell'] = ve_bell(T, p)
        if not ves: break
        row['used'].append(round(M0 - m + DM, 2)); row['p_bar'].append(round(p / 1e5, 2)); row['T_C'].append(round(T - 273.15, 2))
        for k in alive:
            if k in ves and alive[k]: row['I'][k].append(round(row['I'][k][-1] + ves[k] * DM / 1000, 3))  # kN*s
            else:
                alive[k] = False
        m -= DM
    row['used'].insert(0, 0.0)
    out['temps'].append(row)
    print(TC, 'p0', row['p0_bar'], {k: (len(v) - 1) * DM for k, v in row['I'].items()}, {k: v[-1] for k, v in row['I'].items()})
OUT.write_text('// Generated by scripts/build-grok-air-tables.py (CoolProp 8.0.0). Do not edit by hand.\nexport const AIR_TABLES=' + json.dumps(out, separators=(',', ':')) + ';\n')
print('bytes', OUT.stat().st_size)
